// Installs the stable launcher into `<configDir>/bin` and migrates existing
// entry points onto it.
//
// The installed entry must survive the skill directory being half-swapped, so it
// gets a byte-identical vendored copy of `launcher-runtime.mjs` and of its lock
// module (`skill-swap-lock.mjs`) beside it. `launcher.mjs` itself stays in the
// skill tree: it is the installer, and the installer is allowed to be the thing
// that is missing — the launcher it already installed keeps working.

import { chmodSync, copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import * as nodePath from 'node:path'
import { isMainModule } from './is-main.mjs'

export const launcherFileName = 'tokenboard-launcher.mjs'
export const vendoredFiles = ['launcher-runtime.mjs', 'skill-swap-lock.mjs']

// The absolute path a scheduler or hook should invoke. A single source of truth
// so install-schedule, hooks and the migration step agree byte-for-byte.
export function launcherScriptPath(configDir) {
  return join(configDir, 'bin', launcherFileName)
}

function entrySource() {
  return `#!/usr/bin/env node
// Auto-generated by TokenBoard's skill scripts. Do not edit; rerun setup or
// upgrade to refresh. This file is the stable entry that scheduled runs and
// hooks execute so a half-finished skill-directory swap repairs itself.
import { runLauncherCli } from './launcher-runtime.mjs'

process.exitCode = runLauncherCli({ argv: process.argv.slice(2), env: process.env })
`
}

// Idempotent. Rewrites the entry and the vendored modules every call so a stale
// or corrupted install heals on the next setup/upgrade tick.
export function ensureLauncher({ configDir, sourceDir, platform = process.platform }) {
  const binDir = join(configDir, 'bin')
  mkdirSync(binDir, { recursive: true })
  const launcherPath = join(binDir, launcherFileName)
  writeFileSync(launcherPath, entrySource(), { mode: 0o755 })
  if (platform !== 'win32') {
    try {
      chmodSync(launcherPath, 0o755)
    } catch {
      // The scheduler invokes the entry through node, so the mode is a nicety.
    }
  }
  const vendored = []
  for (const name of vendoredFiles) {
    const target = join(binDir, name)
    copyFileSync(join(sourceDir, name), target)
    vendored.push(target)
  }
  return { launcherPath, binDir, vendored }
}

// Kept for tests and for the CLI wrapper below: the vendored copy must never
// drift from the source of truth.
export function assertVendoredMatch({ configDir, sourceDir }) {
  for (const name of vendoredFiles) {
    const installed = readFileSync(join(configDir, 'bin', name), 'utf8')
    const source = readFileSync(join(sourceDir, name), 'utf8')
    if (installed !== source) throw new Error(`${name} in ${configDir}/bin drifted from the skill copy`)
  }
}

export function runLauncherInstallCli(argv = process.argv.slice(2), options = {}) {
  const configDir = options.configDir || launcherConfigDirFrom(options.env || process.env)
  const result = ensureLauncher({
    configDir,
    sourceDir: options.sourceDir || import.meta.dirname,
    platform: options.platform
  })
  console.log(JSON.stringify(result, null, 2))
  return 0
}

// --- entry migration --------------------------------------------------------
//
// Every legacy entry invokes `<skillDir>/scripts/<name>.mjs`. Migration swaps
// that script argument for the launcher while keeping the argument at the same
// position, so the three schedulers, the Claude/Codex hooks and the Antigravity
// statusline all become launcher clients through one rewrite. The launcher then
// takes `<entry> args...` where `<entry>` is the script's path relative to the
// skill directory. It is deliberately narrow: an argument is only replaced when
// its resolved path IS one of THIS install's skill scripts, so a user's
// unrelated custom command is left exactly as-is.
export function migrateScriptArgs({ args, skillDir, launcherPath, path = nodePath }) {
  const scriptsDir = path.resolve(skillDir, 'scripts')
  let changed = false
  const next = args.map((arg) => {
    if (typeof arg !== 'string') return arg
    const bare = stripQuotes(arg)
    if (!path.isAbsolute(bare)) return arg
    const resolved = path.resolve(bare)
    if (path.dirname(resolved) !== scriptsDir || !resolved.endsWith('.mjs')) return arg
    changed = true
    return arg.startsWith('"') ? `"${launcherPath}"` : arg.startsWith("'") ? `'${launcherPath}'` : launcherPath
  })
  return { args: next, changed }
}

// The argument the launcher receives for a given legacy skill script. The
// launcher spawns `<skillDir>/<this> args...`, so the script-relative path is
// what the caller asked for: `scripts/sync.mjs`.
export function launcherRelativeScript(scriptPath, skillDir, path = nodePath) {
  const relative = path.relative(path.resolve(skillDir), path.resolve(stripQuotes(scriptPath)))
  return relative.split(path.sep).join('/')
}

export function stripQuotes(value) {
  const s = String(value)
  if ((s.startsWith('"') && s.endsWith('"')) || (s.startsWith("'") && s.endsWith("'"))) {
    return s.slice(1, -1)
  }
  return s
}

function launcherConfigDirFrom(env) {
  const { homedir } = process.getBuiltinModule('node:os')
  return env.TOKENBOARD_STATE_DIR || env.TOKENBOARD_CONFIG_DIR || join(homedir(), '.tokenboard')
}

if (isMainModule(import.meta.url)) {
  process.exitCode = runLauncherInstallCli()
}
